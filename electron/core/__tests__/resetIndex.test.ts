// Rebuilding the index keeps file ids (#262): resetIndex soft-deletes the rows
// and the scan that follows revives them in place.
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import fs from "node:fs";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { openDb, type DB } from "../db.js";
import { deleteFromIndex, upsertScanRoot } from "../queries.js";
import { syncFiles, walk } from "../scan.js";
import { syncFts } from "../tags.js";
import { resetIndex } from "../jobs.js";

describe("resetIndex", () => {
  let db: DB;
  let root: string;
  let thumbs: string;
  let rootId: number;
  let core: Parameters<typeof resetIndex>[0];

  beforeEach(async () => {
    db = openDb(":memory:", ":memory:");
    root = await fsp.mkdtemp(path.join(os.tmpdir(), "meguri-rebuild-"));
    thumbs = await fsp.mkdtemp(
      path.join(os.tmpdir(), "meguri-rebuild-thumbs-"),
    );
    rootId = upsertScanRoot(db, root, "deadbeef");
    core = { db, rootId, thumbsDir: () => thumbs };
  });
  afterEach(async () => {
    db.close();
    await fsp.rm(root, { recursive: true, force: true });
    await fsp.rm(thumbs, { recursive: true, force: true });
  });

  /** A scan; `rehash` as runScan passes it for a rebuild. */
  async function scan(rehash = false) {
    const res = await syncFiles(db, rootId, await walk(root), { rehash });
    for (const id of [...res.ftsTargets, ...res.ftsMissing]) syncFts(db, id);
    return res;
  }

  function row(id: number) {
    return db
      .prepare(
        "SELECT rel_path, deleted_at, excluded_at, thumb_status, thumb_path, width FROM files WHERE id = ?",
      )
      .get(id) as {
      rel_path: string;
      deleted_at: number | null;
      excluded_at: number | null;
      thumb_status: string;
      thumb_path: string | null;
      width: number | null;
    };
  }

  function idOf(relPath: string): number {
    return (
      db.prepare("SELECT id FROM files WHERE rel_path = ?").get(relPath) as {
        id: number;
      }
    ).id;
  }

  function hasFts(id: number): boolean {
    return (
      db.prepare("SELECT 1 FROM files_fts WHERE rowid = ?").get(id) !==
      undefined
    );
  }

  it("keeps the ids of the files a rebuild finds again", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await fsp.writeFile(path.join(root, "b.mp4"), "BBBBBBBBBB");
    await scan();
    const a = idOf("a.mp4");
    const b = idOf("b.mp4");
    // As if probed and thumbnailed.
    db.prepare(
      "UPDATE files SET width = 1920, thumb_path = 'x.webp', thumb_status = 'done'",
    ).run();
    fs.writeFileSync(path.join(thumbs, `${a}.webp`), "thumb");

    await resetIndex(core, () => false);

    // Soft-deleted, reset for the rescan, out of the search index.
    expect(row(a)).toMatchObject({
      thumb_status: "pending",
      thumb_path: null,
      width: null,
    });
    expect(row(a).deleted_at).not.toBeNull();
    expect(hasFts(a)).toBe(false);
    expect(fs.existsSync(path.join(thumbs, `${a}.webp`))).toBe(false);

    const res = await scan(true);

    expect(res.stats).toMatchObject({ inserted: 0, unchanged: 2 });
    // Unchanged: not auto-tagged again (ftsTargets drives auto-tagging).
    expect(res.ftsTargets).toEqual([]);
    expect(idOf("a.mp4")).toBe(a);
    expect(idOf("b.mp4")).toBe(b);
    expect(row(a).deleted_at).toBeNull();
    expect(row(a).thumb_status).toBe("pending"); // regenerated by the thumbnail pass
    expect(hasFts(a)).toBe(true);
    expect(hasFts(b)).toBe(true);
  });

  it("brings back a file removed from the index, with its id", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    deleteFromIndex(db, a);

    await resetIndex(core, () => false);
    expect(row(a).excluded_at).toBeNull();
    await scan(true);

    expect(idOf("a.mp4")).toBe(a);
    expect(row(a).deleted_at).toBeNull();
    expect(hasFts(a)).toBe(true);
  });

  it("leaves the rows and thumbnails it is told to keep", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    db.prepare(
      "UPDATE files SET thumb_path = 'x.webp', thumb_status = 'done'",
    ).run();
    fs.writeFileSync(path.join(thumbs, `${a}.webp`), "thumb");

    await resetIndex(core, (rel) => rel === "a.mp4");

    expect(row(a)).toMatchObject({
      deleted_at: null,
      thumb_status: "done",
      thumb_path: "x.webp",
    });
    expect(hasFts(a)).toBe(true);
    expect(fs.existsSync(path.join(thumbs, `${a}.webp`))).toBe(true);
  });

  it("leaves a file that went away since the last scan soft-deleted", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    await fsp.rm(path.join(root, "a.mp4"));

    await resetIndex(core, () => false);
    const res = await scan(true);

    expect(res.stats.deleted).toBe(0); // already soft-deleted by the reset
    expect(row(a).deleted_at).not.toBeNull();
    expect(hasFts(a)).toBe(false);
  });

  it("purges the rows of files already gone, but not those removed from the index", async () => {
    await fsp.writeFile(path.join(root, "gone.mp4"), "GGGGGGGGGG");
    await fsp.writeFile(path.join(root, "removed.mp4"), "RRRRRRRRRR");
    await scan();
    const gone = idOf("gone.mp4");
    const removed = idOf("removed.mp4");
    await fsp.rm(path.join(root, "gone.mp4"));
    await scan(); // soft-deletes gone.mp4
    deleteFromIndex(db, removed);

    await resetIndex(core, () => false);

    expect(row(gone)).toBeUndefined();
    expect(row(removed).excluded_at).toBeNull();
    await scan(true);
    expect(row(removed).deleted_at).toBeNull();
  });

  it("revives an unchanged file whose re-hash fails instead of leaving it deleted", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    const discovered = await walk(root);
    await fsp.rm(path.join(root, "a.mp4")); // gone between the walk and the hash

    await resetIndex(core, () => false);
    const res = await syncFiles(db, rootId, discovered, { rehash: true });

    expect(res.unreadable.map((u) => u.relPath)).toEqual(["a.mp4"]);
    expect(res.stats.unchanged).toBe(1);
    expect(row(a).deleted_at).toBeNull();
  });

  it("gives an unchanged row without a hash its hash on a rebuild, as unchanged", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    db.prepare("UPDATE files SET content_hash = NULL WHERE id = ?").run(a);

    await resetIndex(core, () => false);
    const res = await scan(true);

    expect(res.stats).toMatchObject({ unchanged: 1, updated: 0 });
    expect(res.ftsTargets).toEqual([]); // not auto-tagged again
    expect(
      db.prepare("SELECT content_hash FROM files WHERE id = ?").pluck().get(a),
    ).not.toBeNull();
  });

  it("re-classifies an unchanged row whose kind no longer matches its extension", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    db.prepare("UPDATE files SET kind = 'image' WHERE id = ?").run(a);

    const res = await scan();

    expect(res.stats.unchanged).toBe(1);
    expect(
      db.prepare("SELECT kind FROM files WHERE id = ?").pluck().get(a),
    ).toBe("video");
    expect(res.needsThumb).toEqual([a]);
  });

  it("keeps the id of a file renamed just before the rebuild", async () => {
    await fsp.writeFile(path.join(root, "a.mp4"), "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    await fsp.rename(path.join(root, "a.mp4"), path.join(root, "b.mp4"));

    await resetIndex(core, () => false);
    const res = await scan(true);

    expect(res.stats).toMatchObject({ moved: 1, inserted: 0 });
    expect(idOf("b.mp4")).toBe(a);
    expect(row(a).deleted_at).toBeNull();
  });

  it("re-hashes on a rebuild, catching content changed with size and mtime kept", async () => {
    const f = path.join(root, "a.mp4");
    await fsp.writeFile(f, "AAAAAAAAAA");
    await scan();
    const a = idOf("a.mp4");
    const { mtime } = fs.statSync(f);
    // Same size, mtime put back: a plain scan sees no change.
    await fsp.writeFile(f, "BBBBBBBBBB");
    fs.utimesSync(f, mtime, mtime);
    const hashOf = () =>
      (
        db.prepare("SELECT content_hash FROM files WHERE id = ?").get(a) as {
          content_hash: string;
        }
      ).content_hash;
    const before = hashOf();
    expect((await scan()).stats.unchanged).toBe(1);
    expect(hashOf()).toBe(before);

    await resetIndex(core, () => false);
    const res = await scan(true);

    expect(res.stats.updated).toBe(1);
    expect(res.ftsTargets).toEqual([a]);
    expect(idOf("a.mp4")).toBe(a);
    expect(hashOf()).not.toBe(before);
  });
});
