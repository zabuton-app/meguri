const log = scopedLog("scan");

export type JobEvent =
  | {
      type: "progress";
      jobId: string;
      phase: string;
      done: number;
      total: number;
    }
  | { type: "thumbDone"; id: number }
  | { type: "done"; jobId: string; stats: ScanStats; aborted?: boolean };

/**
 * Reset the file index (files + FTS rows for this root) and its thumbnails, so the next
 * scan re-derives them. Rows are soft-deleted rather than deleted, with their
 * probed fields cleared and thumb_status back to 'pending': the scan that follows revives
 * each file that is still there in place, so it keeps its files.id, which user collections
 * and Watch Later refer to (#262). Its FTS row, thumbnail and metadata fields are then
 * rebuilt like a new file's; an unchanged file is not auto-tagged again, though.
 * Rows of files that were already gone are deleted. Durable metadata (file_meta /
 * meta_tags / play_history) is keyed by meta_key and left untouched either way.
 *
 * Note: the removed-from-index exclusions (files.excluded_at) are reset too — a rebuild
 * deliberately clears that list, so files previously removed from the index reappear. This
 * is spelled out in the rebuild confirmation dialog.
 *
 * Rows for which `keep` is true (paths the walk could not read) are left as they are, with
 * their thumbnails: they could not be scanned again now.
 */
export async function resetIndex(
  core: Pick<Core, "db" | "rootId" | "thumbsDir">,
  keep: (relPath: string) => boolean,
): Promise<void> {
  const { db } = core;
  const now = nowUnix();
  const kept = new Set<number>();
  db.transaction(() => {
    const rows = db
      .prepare("SELECT id, rel_path FROM files WHERE root_id = ?")
      .all(core.rootId) as { id: number; rel_path: string }[];
    for (const r of rows) if (keep(r.rel_path)) kept.add(r.id);
    // Set-based, with the kept ids as a JSON array: one statement each instead
    // of one per row.
    const notKept = "id NOT IN (SELECT value FROM json_each(?))";
    const keptJson = JSON.stringify([...kept]);
    db.prepare(
      `DELETE FROM files_fts WHERE rowid IN
         (SELECT id FROM files WHERE root_id = ? AND ${notKept})`,
    ).run(core.rootId, keptJson);
    // Rows of files already gone (soft-deleted, not removed from the index) are
    // purged, as the old delete-everything rebuild did; nothing else ever
    // deletes them.
    db.prepare(
      `DELETE FROM files WHERE root_id = ? AND ${notKept}
         AND deleted_at IS NOT NULL AND excluded_at IS NULL`,
    ).run(core.rootId, keptJson);
    // The probed fields are the ones updateExtractedMeta (queries/meta.ts)
    // writes; keep the two lists in step.
    db.prepare(
      `UPDATE files SET deleted_at = COALESCE(deleted_at, ?), excluded_at = NULL,
         width = NULL, height = NULL, duration = NULL, codec = NULL, fps = NULL,
         captured_at = NULL, meta = NULL, thumb_path = NULL, thumb_status = 'pending'
       WHERE root_id = ? AND ${notKept}`,
    ).run(now, core.rootId, keptJson);
  })();
  // Thumbnails are regenerated by the rescan, so remove them. Async with a small
  // concurrent pool — a synchronous unlink loop over tens of thousands of
  // thumbnails would block the main thread.
  const thumbs = core.thumbsDir();
  let names: string[] = [];
  try {
    names = await fsp.readdir(thumbs);
  } catch {
    return; // thumbs dir may not exist yet
  }
  await pool(names, 8, async (name) => {
    if (kept.has(Number(name.split(".")[0]))) return;
    try {
      await fsp.rm(path.join(thumbs, name), { force: true });
    } catch {
      /* best-effort; a leftover thumb is overwritten by the rescan */
    }
  });
}

export async function runScan(
  core: Core,
  jobId: string,
  onEvent: (e: JobEvent) => void,
  opts: {
    rebuild?: boolean;
    signal?: AbortSignal;
    /** The workspace being scanned, for the configuration's folder rules. */
    workspaceId?: string;
  } & (
    | { autoTag?: undefined; deriveAutoTags?: undefined }
    | {
        /**
         * Reads the auto-tagging configuration (app config) and its version
         * (autoTagSettingsVersion); nothing is tagged when omitted. Read when
         * the tagging starts, not with the scan: settings saved while the
         * files are walked and hashed are the ones the scan tags them with.
         */
        autoTag: () => { config: AutoTagConfig; version: number };
        /** Evaluates the engine: the worker, so a rule cannot stall the scan. */
        deriveAutoTags: DeriveAutoTags;
      }
  ) = {},
): Promise<ScanStats> {
  const { signal } = opts;
  const { db } = core;

  // --- walk + sync (both async with concurrent IO, so they don't block the event loop) ---
  // On SMB these phases dominate the time before thumbnails start, so report their progress.
  // walk() throws when the root cannot be read, before anything below touches
  // the index.
  const unreadablePaths: string[] = [];
  const discovered = await walk(
    core.root,
    (count) =>
      onEvent({
        type: "progress",
        jobId,
        phase: "walk",
        done: count,
        total: 0,
      }),
    signal,
    (relPath) => unreadablePaths.push(relPath),
  );

  if (signal?.aborted) {
    const empty = emptyScanStats();
    onEvent({ type: "done", jobId, stats: empty, aborted: true });
    return empty;
  }

  // Rows walk() could not reach (a folder or file that exists but cannot be
  // read) are kept as they are by the rebuild, the sync and the thumbnails.
  const isUnreadable = unreadableMatcher(unreadablePaths);

  // A rebuild resets the derived file index (keeping file ids and durable
  // metadata) before syncing. Only after the walk, so an unreachable root keeps
  // its index.
  if (opts.rebuild) await resetIndex(core, isUnreadable);

  const { stats, ftsTargets, ftsMissing, unreadable } = await syncFiles(
    db,
    core.rootId,
    discovered,
    {
      onHashProgress: (done, total) =>
        onEvent({ type: "progress", jobId, phase: "hash", done, total }),
      signal,
      unreadablePaths,
      // A rebuild starts over, hashes included.
      rehash: opts.rebuild,
    },
  );
  if (unreadablePaths.length > 0) {
    // A count only: the log may be shared, and folder names can be private.
    log.warn(
      `skipped ${unreadablePaths.length} folder(s) or file(s) that could not be read; their rows are kept as they are`,
    );
  }
  if (unreadable.length > 0) {
    // Only counts per error code: the log is meant to be attached to bug
    // reports, and relative paths or fs error messages would expose media
    // file names that the logger's home-path redaction does not catch.
    const byCode: Record<string, number> = {};
    for (const { code } of unreadable) byCode[code] = (byCode[code] ?? 0) + 1;
    log.warn(
      `skipped ${unreadable.length} file(s) that could not be read:`,
      byCode,
    );
  }
  q.touchScanRoot(db, core.rootId);

  // Tag what this scan added or changed (ftsTargets is exactly that set). Ahead
  // of the FTS sync and the thumbnail pool: the engine reads nothing but file
  // names and where the files are, so its tags need not wait for the slowest
  // phase of the scan.
  let tagged: ReadonlySet<number> = new Set();
  // `derive` read with it: checking opts.autoTag is what tells the type
  // that deriveAutoTags is there.
  const autoTag = opts.autoTag && {
    ...opts.autoTag(),
    derive: opts.deriveAutoTags,
  };
  if (autoTag?.config.applyOnScan) {
    try {
      tagged = await applyAutoTagsOnScan(db, {
        engine: autoTag.config,
        workspaceId: opts.workspaceId,
        derive: autoTag.derive,
        settingsVersion: autoTag.version,
        changedIds: ftsTargets,
        signal,
        onProgress: (d, t) =>
          onEvent({
            type: "progress",
            jobId,
            phase: "tags",
            done: d,
            total: t,
          }),
      });
    } catch (err) {
      // A worker that will not run, or that got stuck with no rule to blame
      // (a rule that does not finish is left out by the worker's client, and
      // the rest carry on), must not cost the scan its thumbnails. The folder
      // rules' tags were added; the files stay owed for what their names give,
      // so the next scan tags them once the cause is gone.
      if (err instanceof AutoTagTimeoutError) {
        log.warn("auto-tagging skipped: the worker got stuck");
      } else if (err instanceof AutoTagUnavailableError) {
        log.warn("auto-tagging skipped: the worker is unavailable");
      } else {
        throw err;
      }
    }
  } else if (autoTag) {
    clearAutoTagPending(db);
  }

  // Sync FTS for new/moved/updated entries and for unchanged rows that have no
  // FTS row (see syncFiles), less those auto tagging re-synced as it tagged them.
  const ftsIds = [...ftsTargets, ...ftsMissing].filter((id) => !tagged.has(id));
  const ftsTotal = ftsIds.length;
  let done = 0;
  for (const id of ftsIds) {
    if (signal?.aborted) break;
    syncFts(db, id);
    done++;
    if (done % 64 === 0 || done === ftsTotal) {
      onEvent({
        type: "progress",
        jobId,
        phase: "index",
        done,
        total: ftsTotal,
      });
      // Yield to the event loop every 256 entries.
      if (done % 256 === 0) await new Promise((r) => setImmediate(r));
    }
  }

  if (signal?.aborted) {
    onEvent({ type: "done", jobId, stats, aborted: true });
    return stats;
  }

  // --- thumbnail/meta (parallel) ---
  // Rows walk() could not reach would only fail here and be marked 'error'
  // for good; leave them pending for a scan that can read them.
  let pending = q.filesNeedingThumb(db, core.rootId);
  if (unreadablePaths.length > 0) {
    pending = pending.filter((f) => !isUnreadable(f.rel_path));
  }
  const total = pending.length;
  let processed = 0;
  const thumbs = core.thumbsDir();

  // Persist results in batches: one transaction per THUMB_FLUSH_EVERY files
  // instead of one implicit commit (+ FTS delete/insert) per file, which
  // multiplied WAL commits by the file count on a full scan. Progress and
  // thumbDone events are emitted per flush (after the commit, so the renderer's
  // thumbnail request sees thumb_status = 'done'), which also throttles the
  // previously per-file scan:progress IPC traffic.
  type ThumbResult = {
    id: number;
    kind: Kind;
    dest: string;
    ok: boolean;
    meta: Awaited<ReturnType<typeof extractMeta>>;
    /** Set for audio files that carry no embedded cover art, which is a normal
     *  state rather than a failure. Such rows still need their metadata persisted
     *  (duration drives the UI), but must land on thumb_status 'done' with a null
     *  path — not 'error', which would misreport a file that is perfectly fine,
     *  and not left 'pending', which would keep them in filesNeedingThumb forever
     *  and inflate every later scan's progress total. Adding art to such a file
     *  later is still picked up: writing the tag changes size/mtime, which
     *  syncFiles() resets back to 'pending'. */
    skipThumb?: boolean;
  };
  const THUMB_FLUSH_EVERY = 32;
  let buffer: ThumbResult[] = [];

  const persistOne = (r: ThumbResult): void => {
    q.updateExtractedMeta(db, r.id, r.meta);
    if (r.skipThumb) {
      q.setThumb(db, r.id, null, "done");
    } else {
      q.setThumb(db, r.id, r.ok ? r.dest : null, r.ok ? "done" : "error");
    }
    // Derive from what was just written, and before syncFts — which rebuilds
    // tags_text by re-reading meta_tags.
    applyAutoMetaTags(db, r.id, { kind: r.kind, ...r.meta });
    syncFts(db, r.id);
  };
  // Per-file transaction for the retry path: persistOne spans several writes
  // (incl. the FTS delete+insert), so a mid-way failure must roll back the
  // whole file rather than leave partial state (e.g. an FTS row deleted but
  // never re-inserted).
  const persistOneTx = db.transaction(persistOne);

  const flush = (): void => {
    if (buffer.length === 0) return;
    const batch = buffer;
    buffer = [];
    const persisted: ThumbResult[] = [];
    try {
      db.transaction(() => {
        for (const r of batch) persistOne(r);
      })();
      persisted.push(...batch);
    } catch (e) {
      // A DB error (SQLITE_BUSY, disk full, constraint) rolls back the whole
      // batch; retry per file so one bad row can't discard its batchmates.
      // Files that still fail stay 'pending' and are retried next scan.
      log.warn("thumb/meta batch persist failed, retrying per file:", e);
      for (const r of batch) {
        try {
          persistOneTx(r);
          persisted.push(r);
        } catch (err) {
          log.warn(`failed to persist thumb/meta for file ${r.id}:`, err);
        }
      }
    }
    for (const r of persisted) {
      if (r.ok) onEvent({ type: "thumbDone", id: r.id });
    }
    // Only successfully persisted rows advance the progress counter — failed
    // rows stay 'pending' and are retried next scan (same as the old per-file
    // semantics, where a failed persist did not count as done).
    processed += persisted.length;
    onEvent({
      type: "progress",
      jobId,
      phase: "thumbnail",
      done: processed,
      total,
    });
  };

  // Per-file worker. Never throws: a pool worker that rejects would abandon
  // its siblings mid-flight (still writing to this DB after the scan has
  // reported as finished), so per-file failures are logged and the file is
  // left 'pending' for the next scan. Failures are counted so a tool that is
  // broken outright (every file failing) still surfaces as a scan error.
  let failed = 0;
  // Audio without cover art never attempts a thumbnail, so it counts towards
  // neither success nor failure of the tooling — it is taken out of the
  // denominator of the all-failed check below.
  let skipped = 0;
  const processOne = async (f: (typeof pending)[number]): Promise<void> => {
    if (signal?.aborted) return;
    const kind = f.kind as Kind;
    const dest = path.join(thumbs, `${f.id}.webp`);
    try {
      // ffprobe runs outside the decode slot: it doesn't decode, but it can be
      // slow on network shares and must not hold a decoder up meanwhile.
      const meta = await extractMeta(f.abs_path, kind, signal);

      // Audio always needs its metadata (duration), and gets a thumbnail only
      // when the file embeds cover art.
      if (kind === "audio") {
        if (signal?.aborted) return;
        // A failed probe (timeout, transient IO error, unparseable output)
        // yields `raw: null`, so whether the file has cover art is unknown.
        // Record it as 'error' — the same terminal state a video whose probe
        // failed lands in — rather than leaving it 'pending': a pending row is
        // re-probed on every scan (up to the 60 s ffprobe timeout each time)
        // and never counts towards the progress total. A later change to the
        // file resets it to 'pending' through syncFiles() like any other row.
        if (meta.raw == null) {
          failed++;
          buffer.push({ id: f.id, kind, dest, ok: false, meta });
          if (buffer.length >= THUMB_FLUSH_EVERY) flush();
          return;
        }
        const coverIndex = coverArtStreamIndex(meta.raw);
        if (coverIndex == null) {
          skipped++;
          buffer.push({
            id: f.id,
            kind,
            dest,
            ok: false,
            meta,
            skipThumb: true,
          });
          if (buffer.length >= THUMB_FLUSH_EVERY) flush();
          return;
        }
        // Embedded artwork has no size limit (multi-megapixel scans are
        // common), so it takes a decode slot like any other expensive decode
        // instead of adding a pool's worth of ffmpeg processes on top.
        const coverOk = await withScanDecodeSlot(
          () =>
            generateThumb(
              f.abs_path,
              kind,
              dest,
              signal,
              undefined,
              coverIndex,
            ),
          signal,
        );
        if (signal?.aborted) return;
        // Extraction failure here is a real error (the probe said a picture is
        // present), so let it record as 'error' like the video/image path.
        if (!coverOk) failed++;
        buffer.push({ id: f.id, kind, dest, ok: coverOk, meta });
        if (buffer.length >= THUMB_FLUSH_EVERY) flush();
        return;
      }

      // Honour a user-chosen thumbnail frame if one was set previously. Ignored for images.
      const offsetSec =
        kind === "video" ? (q.thumbOffsetOf(db, f.id) ?? undefined) : undefined;
      const thumb = () =>
        generateThumb(f.abs_path, kind, dest, signal, offsetSec);
      // Only the expensive decodes take a slot: every video, and images big
      // enough to cost hundreds of MB — or of unknown size (ffprobe failed, or
      // a tiled HEIF/AVIF that extractMeta leaves unsized), which are treated
      // as big. Everything else runs at pool width.
      const pixels =
        meta.width != null && meta.height != null
          ? meta.width * meta.height
          : Infinity;
      const expensive = kind === "video" || pixels >= LARGE_IMAGE_PIXELS;
      const ok = expensive
        ? await withScanDecodeSlot(thumb, signal)
        : await thumb();

      // If aborted mid-flight, ffprobe/ffmpeg were killed and returned partial/empty
      // results. Don't persist them or mark the file 'error' (which filesNeedingThumb
      // skips on rescan) — leave it 'pending' so the next scan retries it.
      if (signal?.aborted) return;

      // ffmpeg reporting failure counts too, so a broken ffmpeg (every file
      // marked 'error') is caught by the all-failed check below.
      if (!ok) failed++;
      // Workers share the event loop, so buffering + flushing is race-free.
      buffer.push({ id: f.id, kind, dest, ok, meta });
      if (buffer.length >= THUMB_FLUSH_EVERY) flush();
    } catch (err) {
      if (signal?.aborted) return;
      failed++;
      log.warn(`thumbnail worker failed for ${f.id}:`, err);
    }
  };
  // Images and videos run in separate pools (mediaConcurrency.ts has the
  // width and the reasoning): a run of videos must not block the cheap image
  // side, and the expensive decodes are bounded process-wide inside
  // processOne, together with the media server's. Both pools are awaited to
  // completion regardless of failure, and whatever completed is persisted
  // before any failure propagates.
  const images = pending.filter((f) => f.kind !== "video");
  const videos = pending.filter((f) => f.kind === "video");
  try {
    const results = await Promise.allSettled([
      pool(images, SCAN_POOL_WIDTH, processOne, signal),
      pool(videos, SCAN_POOL_WIDTH, processOne, signal),
    ]);
    for (const r of results) if (r.status === "rejected") throw r.reason;
  } finally {
    // Persist the tail batch. On abort the buffered results are from ffmpeg
    // runs that completed before the signal fired, so they are safe to keep.
    flush();
  }

  // Files classified as unchanged/moved never enter the pool above (syncFiles
  // leaves their thumb_status alone), so an existing library only gains derived
  // tags through this pass. It reads the ffprobe columns already on `files`, so
  // no media file is touched.
  if (!signal?.aborted && needsAutoMetaBackfill(db)) {
    await backfillAutoMetaTags(db, {
      signal,
      onProgress: (d, t) =>
        onEvent({ type: "progress", jobId, phase: "tags", done: d, total: t }),
    });
  }

  // Tags left on no file (pruneUnusedTags keeps metadata itself: it is shared).
  if (!signal?.aborted) q.pruneUnusedTags(db);

  // Every file failing points at the tooling, not the files. Reported
  // regardless of batch size: a tiny incremental scan may flag a merely
  // corrupt file, but the alternative — a broken ffmpeg hiding behind small
  // scans and reporting success with zero thumbnails — is worse. Raised only
  // after the backfill/prune passes above, so a file that fails on every scan
  // cannot starve them indefinitely.
  const attempted = pending.length - skipped;
  if (failed > 0 && failed === attempted && !signal?.aborted) {
    throw new Error(
      `thumbnail extraction failed for all ${failed} attempted file(s) (is ffmpeg/ffprobe working?)`,
    );
  }

  onEvent({ type: "done", jobId, stats, aborted: signal?.aborted });
  return stats;
}
